# =============================================================================
# THE TURN LOOP — how this all comes together
# =============================================================================
# Sketched as a dataflow comment, not code. Annotated by what's deterministic
# vs LLM-generated.
#
# 1. Engine resolves phase. -> deterministic
#    Captures MoveEvents, AdjustmentEvents, PhaseState into Layer 0.
#
# 2. grade_open_commitments() runs. -> deterministic
#    grade_open_predictions() runs. -> deterministic
#    update_credibility_from_commitments() runs. -> deterministic
#    lifecycle_review_plans() runs. -> deterministic
#    lifecycle_review_intent_commitments() runs. -> deterministic
#
# 3. Belief lifecycle pass: -> deterministic except revision proposal
#    promote_proto_beliefs, retire_active_beliefs, invite_revisions (LLM here),
#    decay_idle.
#
# 4. Strategy lifecycle pass: -> deterministic except revision proposal
#    promote_proto_intents, retire_active_intents, invite_intent_revisions
#    (LLM here). Active intents whose commitment windows just closed are
#    SUCCEEDED or FAILED based on prediction confirmation rate + sc_delta.
#
# 5. New phase begins. Build TurnFovea for this agent. -> deterministic
#    Per-addressee slot selection: pick the most relevant active belief,
#    soonest open commitment in/out, the actively-committed strategic intent
#    (if any). Plan nodes from the previous phase are NOT shown — they're
#    bookkeeping for the lifecycle, not for the prompt.
#
# 6. Negotiate call. -> LLM
#    Prompt contains: character_brief, fovea.render(), recent_messages_digest,
#    board_tag, addressees, COMMITSPEAK GRAMMAR REMINDER. LLM emits messages
#    with optional commitspeak tails. Tails are parsed at message-send time;
#    only well-formed lines become CommitmentNodes / SelfCommitmentNodes.
#
# 7. Parse commitspeak from outgoing messages we sent THIS turn (register as
#    SelfCommitmentNodes). Parse commitspeak from incoming messages addressed
#    to us (register as CommitmentNodes). Malformed lines logged for debug.
#    No NL extraction — promises in prose are not tracked.  -> deterministic
#
# 8. Orders call. -> LLM
#    Prompt contains: character_brief, fovea.render(), the actively-
#    committed strategic intent's head (if any), legal moves, and a
#    COMMITSPEAK + PREDICTION REQUIREMENT REMINDER.
#    LLM is REQUIRED to emit:
#      - one order per unit
#      - one PlanNode (head + body, naming parent_intent_id if any)
#      - at least one prediction with window_kind=NEAR_TERM
#      - optional additional predictions with window_kind=LONG_HORIZON
#      - optional proposed proto_belief or proto_intent
#    If the LLM fails to emit a near-term prediction, the orders response is
#    rejected and the prompt is re-issued with a pointed reminder. After two
#    failed attempts, the system synthesizes a default near-term prediction
#    from the issued orders ("you ordered A WAR -> GAL, so I'll register
#    'we predict A WAR moves to GAL by next phase'") so the lifecycle still
#    gets signal.
#
# 9. Register new predictions, plan_node, proto_belief, proto_intent as nodes.
#    All validated structurally; malformed entries are logged but do not
#    enter the graph.  -> deterministic
#
# 10. Engine resolves orders → goto step 1.

