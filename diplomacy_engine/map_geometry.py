# MAO_S is a visual-only second blob; the engine knows only "MAO".
# We store it under a distinct key so the SVG draws both blobs but
# all logic uses MAO. The frontend will draw both blobs labelled "MAO".


def get_geometry(prov: str) -> dict | None:
    return GEOMETRY.get(prov)


def all_drawn_codes() -> list[str]:
    """Codes the SVG should iterate (includes the visual-only MAO_S)."""
    return list(GEOMETRY.keys())


def logical_code(drawn: str) -> str:
    """Map a drawn code to the engine's logical province code."""
    if drawn == "MAO_S":
        return "MAO"
    return drawn
